CREATE OR REPLACE PACKAGE BODY HRMS_RULES AS
    FUNCTION VERSION RETURN VARCHAR2 IS
    BEGIN
        RETURN '1';
    END VERSION;

    PROCEDURE LOCK_DEPARTMENT(P_ID IN NUMBER, P_REQUIRE_ACTIVE IN NUMBER) IS
        V_ACTIVE NUMBER;
    BEGIN
        SELECT IS_ACTIVE INTO V_ACTIVE FROM DEPARTMENT WHERE ID = P_ID FOR UPDATE WAIT 5;
        IF P_REQUIRE_ACTIVE = 1 AND V_ACTIVE <> 1 THEN
            RAISE_APPLICATION_ERROR(-20001, 'DEPARTMENT_INACTIVE');
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20003, 'DEPARTMENT_NOT_FOUND');
    END LOCK_DEPARTMENT;

    PROCEDURE LOCK_FOR_ASSIGNMENT(P_OLD_ID IN NUMBER, P_NEW_ID IN NUMBER) IS
        V_FIRST NUMBER;
        V_SECOND NUMBER;
    BEGIN
        IF P_OLD_ID IS NULL OR P_NEW_ID IS NULL OR P_OLD_ID <= 0 OR P_NEW_ID <= 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'DEPARTMENT_NOT_FOUND');
        END IF;
        V_FIRST := LEAST(P_OLD_ID, P_NEW_ID);
        V_SECOND := GREATEST(P_OLD_ID, P_NEW_ID);
        IF V_FIRST = P_NEW_ID THEN
            LOCK_DEPARTMENT(V_FIRST, 1);
        ELSE
            LOCK_DEPARTMENT(V_FIRST, 0);
        END IF;
        IF V_SECOND <> V_FIRST THEN
            IF V_SECOND = P_NEW_ID THEN
                LOCK_DEPARTMENT(V_SECOND, 1);
            ELSE
                LOCK_DEPARTMENT(V_SECOND, 0);
            END IF;
        END IF;
    END LOCK_FOR_ASSIGNMENT;

    PROCEDURE ASSERT_DEPARTMENT_EMPTY(P_ID IN NUMBER) IS
        V_COUNT NUMBER;
    BEGIN
        LOCK_DEPARTMENT(P_ID, 0);
        SELECT COUNT(*) INTO V_COUNT FROM EMPLOYEE WHERE DEPARTMENT_ID = P_ID AND IS_ACTIVE = 1;
        IF V_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'ACTIVE_EMPLOYEES_EXIST');
        END IF;
    END ASSERT_DEPARTMENT_EMPTY;
END HRMS_RULES;
