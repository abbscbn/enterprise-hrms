CREATE OR REPLACE PACKAGE BODY HRMS_ENTERPRISE AS
    FUNCTION VERSION RETURN VARCHAR2 IS
    BEGIN
        RETURN '1';
    END VERSION;
    PROCEDURE LOCK_ORGANIZATION IS
        V_ID NUMBER;
    BEGIN
        SELECT ID INTO V_ID FROM HRMS_HIERARCHY_GUARD WHERE ID = 1 FOR UPDATE WAIT 5;
    END LOCK_ORGANIZATION;
    PROCEDURE ASSERT_MANAGER(P_MANAGER IN NUMBER) IS
        V_COUNT NUMBER;
    BEGIN
        IF P_MANAGER IS NOT NULL THEN
            SELECT COUNT(*) INTO V_COUNT FROM EMPLOYEE WHERE ID = P_MANAGER AND IS_ACTIVE = 1;
            IF V_COUNT <> 1 THEN
                RAISE_APPLICATION_ERROR(-20005, 'MANAGER_NOT_ACTIVE');
            END IF;
        END IF;
    END ASSERT_MANAGER;
    PROCEDURE SET_EMPLOYEE_MANAGER(P_EMPLOYEE IN NUMBER, P_MANAGER IN NUMBER) IS
        V_COUNT NUMBER;
    BEGIN
        LOCK_ORGANIZATION;
        ASSERT_MANAGER(P_MANAGER);
        IF P_MANAGER IS NOT NULL THEN
            IF P_MANAGER = P_EMPLOYEE THEN
                RAISE_APPLICATION_ERROR(-20004, 'EMPLOYEE_CYCLE');
            END IF;
            SELECT COUNT(*) INTO V_COUNT FROM (
                SELECT EMPLOYEE_ID FROM EMPLOYEE_PROFILE
                START WITH EMPLOYEE_ID = P_MANAGER
                CONNECT BY NOCYCLE PRIOR MANAGER_ID = EMPLOYEE_ID
            ) WHERE EMPLOYEE_ID = P_EMPLOYEE;
            IF V_COUNT > 0 THEN
                RAISE_APPLICATION_ERROR(-20004, 'EMPLOYEE_CYCLE');
            END IF;
        END IF;
        MERGE INTO EMPLOYEE_PROFILE T USING (SELECT P_EMPLOYEE AS ID FROM DUAL) S
        ON (T.EMPLOYEE_ID = S.ID)
        WHEN MATCHED THEN UPDATE SET T.MANAGER_ID = P_MANAGER
        WHEN NOT MATCHED THEN INSERT (EMPLOYEE_ID, MANAGER_ID) VALUES (P_EMPLOYEE, P_MANAGER);
    END SET_EMPLOYEE_MANAGER;
    PROCEDURE SET_DEPARTMENT_PARENT(P_DEPARTMENT IN NUMBER, P_PARENT IN NUMBER) IS
        V_COUNT NUMBER;
    BEGIN
        LOCK_ORGANIZATION;
        IF P_PARENT IS NOT NULL THEN
            SELECT COUNT(*) INTO V_COUNT FROM DEPARTMENT WHERE ID = P_PARENT;
            IF V_COUNT <> 1 THEN
                RAISE_APPLICATION_ERROR(-20006, 'PARENT_NOT_FOUND');
            END IF;
            IF P_PARENT = P_DEPARTMENT THEN
                RAISE_APPLICATION_ERROR(-20004, 'DEPARTMENT_CYCLE');
            END IF;
            SELECT COUNT(*) INTO V_COUNT FROM (
                SELECT DEPARTMENT_ID FROM DEPARTMENT_PROFILE
                START WITH DEPARTMENT_ID = P_PARENT
                CONNECT BY NOCYCLE PRIOR PARENT_ID = DEPARTMENT_ID
            ) WHERE DEPARTMENT_ID = P_DEPARTMENT;
            IF V_COUNT > 0 THEN
                RAISE_APPLICATION_ERROR(-20004, 'DEPARTMENT_CYCLE');
            END IF;
        END IF;
        MERGE INTO DEPARTMENT_PROFILE T USING (SELECT P_DEPARTMENT AS ID FROM DUAL) S
        ON (T.DEPARTMENT_ID = S.ID)
        WHEN MATCHED THEN UPDATE SET T.PARENT_ID = P_PARENT
        WHEN NOT MATCHED THEN INSERT (DEPARTMENT_ID, PARENT_ID) VALUES (P_DEPARTMENT, P_PARENT);
    END SET_DEPARTMENT_PARENT;
END HRMS_ENTERPRISE;
