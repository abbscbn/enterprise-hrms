CREATE TABLE HRMS_REFRESH_USED (
    TOKEN_HASH VARCHAR2(64 CHAR) NOT NULL,
    SESSION_ID VARCHAR2(36 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HRMS_REFRESH_USED PRIMARY KEY (TOKEN_HASH),
    CONSTRAINT FK_HRMS_REFRESH_SESSION FOREIGN KEY (SESSION_ID) REFERENCES HRMS_SESSION(ID)
);
