CREATE TABLE DEPARTMENT_PROFILE (
    DEPARTMENT_ID NUMBER(19,0) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    MANAGER_ID NUMBER(19,0),
    PARENT_ID NUMBER(19,0),
    CREATED_BY NUMBER(19,0),
    UPDATED_BY NUMBER(19,0),
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT PK_DEPARTMENT_PROFILE PRIMARY KEY (DEPARTMENT_ID),
    CONSTRAINT FK_DEP_PROF_DEPARTMENT FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENT(ID),
    CONSTRAINT FK_DEP_PROF_PARENT FOREIGN KEY (PARENT_ID) REFERENCES DEPARTMENT(ID),
    CONSTRAINT FK_DEP_PROF_MANAGER FOREIGN KEY (MANAGER_ID) REFERENCES EMPLOYEE(ID),
    CONSTRAINT FK_DEP_PROF_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES HRMS_USER(ID),
    CONSTRAINT FK_DEP_PROF_UPDATER FOREIGN KEY (UPDATED_BY) REFERENCES HRMS_USER(ID),
    CONSTRAINT CK_DEP_PROF_SELF CHECK (PARENT_ID <> DEPARTMENT_ID)
);
