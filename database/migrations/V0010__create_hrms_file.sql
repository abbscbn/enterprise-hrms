CREATE TABLE HRMS_FILE (
    ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY,
    EMPLOYEE_ID NUMBER(19,0) NOT NULL,
    CATEGORY VARCHAR2(20 CHAR) NOT NULL,
    DOCUMENT_TYPE VARCHAR2(30 CHAR) NOT NULL,
    ORIGINAL_NAME VARCHAR2(255 CHAR) NOT NULL,
    STORAGE_KEY VARCHAR2(80 CHAR) NOT NULL,
    MIME_TYPE VARCHAR2(100 CHAR) NOT NULL,
    SIZE_BYTES NUMBER(10,0) NOT NULL,
    CHECKSUM VARCHAR2(64 CHAR) NOT NULL,
    UPLOADED_BY NUMBER(19,0) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    VISIBILITY VARCHAR2(20 CHAR) NOT NULL,
    ARCHIVED_AT TIMESTAMP(6) WITH TIME ZONE,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HRMS_FILE PRIMARY KEY (ID),
    CONSTRAINT UQ_HRMS_FILE_STORAGE UNIQUE (STORAGE_KEY),
    CONSTRAINT FK_HRMS_FILE_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(ID),
    CONSTRAINT FK_HRMS_FILE_UPLOADER FOREIGN KEY (UPLOADED_BY) REFERENCES HRMS_USER(ID),
    CONSTRAINT CK_HRMS_FILE_CATEGORY CHECK (CATEGORY IN ('PHOTO','DOCUMENT')),
    CONSTRAINT CK_HRMS_FILE_VISIBILITY CHECK (VISIBILITY IN ('SELF','HR_ONLY','ADMIN_ONLY')),
    CONSTRAINT CK_HRMS_FILE_SIZE CHECK (SIZE_BYTES > 0)
);
