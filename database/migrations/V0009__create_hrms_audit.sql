CREATE TABLE HRMS_AUDIT (
    ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY,
    ACTOR_ID NUMBER(19,0),
    ACTION VARCHAR2(60 CHAR) NOT NULL,
    ENTITY_TYPE VARCHAR2(30 CHAR) NOT NULL,
    ENTITY_ID NUMBER(19,0),
    OUTCOME VARCHAR2(20 CHAR) NOT NULL,
    REQUEST_ID VARCHAR2(36 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HRMS_AUDIT PRIMARY KEY (ID),
    CONSTRAINT FK_HRMS_AUDIT_ACTOR FOREIGN KEY (ACTOR_ID) REFERENCES HRMS_USER(ID)
);
