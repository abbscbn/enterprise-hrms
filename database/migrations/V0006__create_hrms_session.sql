CREATE TABLE HRMS_SESSION (
    ID VARCHAR2(36 CHAR) NOT NULL,
    USER_ID NUMBER(19,0) NOT NULL,
    ACCESS_HASH VARCHAR2(64 CHAR) NOT NULL,
    REFRESH_HASH VARCHAR2(64 CHAR) NOT NULL,
    CSRF_HASH VARCHAR2(64 CHAR) NOT NULL,
    EXPIRES_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    REFRESH_EXPIRES_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    REVOKED_AT TIMESTAMP(6) WITH TIME ZONE,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HRMS_SESSION PRIMARY KEY (ID),
    CONSTRAINT UQ_HRMS_SESSION_ACCESS UNIQUE (ACCESS_HASH),
    CONSTRAINT UQ_HRMS_SESSION_REFRESH UNIQUE (REFRESH_HASH),
    CONSTRAINT FK_HRMS_SESSION_USER FOREIGN KEY (USER_ID) REFERENCES HRMS_USER(ID)
);
