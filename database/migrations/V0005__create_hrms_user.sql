CREATE TABLE HRMS_USER (
    ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY,
    USERNAME VARCHAR2(80 CHAR) NOT NULL,
    EMAIL VARCHAR2(254 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(512 CHAR) NOT NULL,
    ROLE_CODE VARCHAR2(20 CHAR) NOT NULL,
    EMPLOYEE_ID NUMBER(19,0),
    IS_ACTIVE NUMBER(1,0) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HRMS_USER PRIMARY KEY (ID),
    CONSTRAINT UQ_HRMS_USER_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_HRMS_USER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UQ_HRMS_USER_EMPLOYEE UNIQUE (EMPLOYEE_ID),
    CONSTRAINT FK_HRMS_USER_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(ID),
    CONSTRAINT CK_HRMS_USER_ROLE CHECK (ROLE_CODE IN ('ADMIN','HR_MANAGER','EMPLOYEE')),
    CONSTRAINT CK_HRMS_USER_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);
