CREATE TABLE HRMS_OUTBOX (
    ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY,
    EVENT_ID VARCHAR2(36 CHAR) NOT NULL,
    EVENT_TYPE VARCHAR2(40 CHAR) NOT NULL,
    PAYLOAD CLOB NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    PUBLISHED_AT TIMESTAMP(6) WITH TIME ZONE,
    ATTEMPTS NUMBER(10,0) NOT NULL,
    CONSTRAINT PK_HRMS_OUTBOX PRIMARY KEY (ID),
    CONSTRAINT UQ_HRMS_OUTBOX_EVENT UNIQUE (EVENT_ID)
);
