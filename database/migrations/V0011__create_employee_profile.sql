CREATE TABLE EMPLOYEE_PROFILE (
    EMPLOYEE_ID NUMBER(19,0) NOT NULL,
    PERSONAL_EMAIL VARCHAR2(254 CHAR),
    PHONE_NUMBER VARCHAR2(30 CHAR),
    JOB_TITLE VARCHAR2(150 CHAR),
    MANAGER_ID NUMBER(19,0),
    EMPLOYMENT_TYPE VARCHAR2(20 CHAR),
    EMPLOYMENT_STATUS VARCHAR2(20 CHAR),
    WORK_LOCATION VARCHAR2(150 CHAR),
    PHOTO_ID NUMBER(19,0),
    CREATED_BY NUMBER(19,0),
    UPDATED_BY NUMBER(19,0),
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT PK_EMPLOYEE_PROFILE PRIMARY KEY (EMPLOYEE_ID),
    CONSTRAINT FK_EMP_PROF_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(ID),
    CONSTRAINT FK_EMP_PROF_MANAGER FOREIGN KEY (MANAGER_ID) REFERENCES EMPLOYEE(ID),
    CONSTRAINT FK_EMP_PROF_PHOTO FOREIGN KEY (PHOTO_ID) REFERENCES HRMS_FILE(ID),
    CONSTRAINT FK_EMP_PROF_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES HRMS_USER(ID),
    CONSTRAINT FK_EMP_PROF_UPDATER FOREIGN KEY (UPDATED_BY) REFERENCES HRMS_USER(ID),
    CONSTRAINT CK_EMP_PROF_SELF CHECK (MANAGER_ID <> EMPLOYEE_ID),
    CONSTRAINT CK_EMP_PROF_TYPE CHECK (EMPLOYMENT_TYPE IN ('FULL_TIME','PART_TIME','CONTRACT','INTERN','UNSPECIFIED')),
    CONSTRAINT CK_EMP_PROF_STATUS CHECK (EMPLOYMENT_STATUS IN ('ACTIVE','ON_LEAVE','TERMINATED'))
);
